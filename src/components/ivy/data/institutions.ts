export const getInstitutionsByCategory = (
  categoryId: string
): Institution[] => {
  return institutions.filter((inst) => inst.category === categoryId);
};

export const getInstitutionById = (id: string): Institution | undefined => {
  return institutions.find((inst) => inst.id === id);
};
